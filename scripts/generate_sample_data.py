def write_services(services, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    for s in services:
        path = os.path.join(out_dir, f"{s['serviceId']}.json")
        with open(path, "w") as f:
            json.dump(s, f, indent=2)
        print(f"  wrote {path}")
    print(f"\nTotal: {len(services)} files")


