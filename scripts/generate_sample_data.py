# Demo regions per provider. Each service picks a stable index by serviceId so
# the Region facet/dimension has variety across the catalog.
_REGIONS = {
    "aws": ["us-east-1", "us-west-2", "eu-west-1"],
    "azure": ["eastus", "westeurope"],
    "on-prem": ["dc-atlanta", "dc-denver"],
}

def _region_for(provider, seed):
    opts = _REGIONS.get(provider)
    return opts[seed % len(opts)] if opts else None

def svc(service_id, name, team, team_email, lifecycle, tier, runtime, framework,
        product, value_stream, description, data_class, deps=None,
        resources=None, datastores=None, features=None, tags=None):
    obj = {
        "$schema": "https://service-catalog.internal/schemas/service-catalog.schema.json",
        "serviceId": service_id,
        "name": name,
        "description": description,
        "lifecycle": lifecycle,
        "criticalityTier": tier,
        "repository": f"https://github.com/acme/{service_id}",
        "provisionerRepoURL": f"https://github.com/acme/{service_id}-provisioner",
        "runtime": runtime,
        "softwareFramework": framework,
        "team": team,
        "teamEmail": team_email,
        "product": product,
        "valueStream": value_stream,
        "dataClassification": data_class,
    }
    if deps:
        obj["dependencies"] = deps
    if resources:
        seed = sum(ord(c) for c in service_id)
        for r in resources:
            if isinstance(r, dict) and "region" not in r:
                reg = _region_for(r.get("provider"), seed)
                if reg:
                    r["region"] = reg
        obj["resources"] = resources
    if datastores:
        obj["datastores"] = datastores
    if features:
        obj["features"] = features
    if tags:
        obj["tags"] = tags
    return obj

def dep(service_id, interaction, critical, purpose, external=False, endpoint=None):
    d = {"serviceId": service_id, "interaction": interaction, "critical": critical,
         "purpose": purpose, "external": external}
    if endpoint:
        d["endpoint"] = endpoint
    return d

